    /**
     * @param  array<int, array<string, mixed>>  $rows
     */
    private function makeChartSection(string $title, string $type, array $rows, int|float $total): array
    {
        return [
            'title' => $title,
            'type' => $type,
            'rows' => array_values($rows),
            'total' => $total,
        ];
    }

    /**
     * @return array<int, array{label: string, requests: int, completed: int}>
     */
    private function getMonthlyRequestsAppendix(Carbon $end): array
    {
        $rows = [];

        for ($i = 11; $i >= 0; $i--) {
            $date = $end->copy()->startOfMonth()->subMonths($i);
            $monthStart = $date->copy()->startOfMonth();
            $monthEnd = $date->copy()->endOfMonth()->min($end->copy()->endOfDay());

            $rows[] = [
                'label' => $date->format('M Y'),
                'requests' => TestRequest::whereBetween('created_at', [$monthStart, $monthEnd])
                    ->count(),
                'completed' => TestRequest::whereIn('status', ['completed', 'delivered'])
                    ->whereBetween('completed_at', [$monthStart, $monthEnd])
                    ->count(),
            ];
        }

        return $rows;
    }

    /**
     * @return array<int, array{label: string, samples: int, target: float}>
     */
    private function getMonthlySamplesAppendix(Carbon $end): array
    {
        $rows = [];
        $monthlyTarget = round(200 / 12, 1);

        for ($i = 11; $i >= 0; $i--) {
            $date = $end->copy()->startOfMonth()->subMonths($i);
            $monthStart = $date->copy()->startOfMonth();
            $monthEnd = $date->copy()->endOfMonth()->min($end->copy()->endOfDay());

            $rows[] = [
                'label' => $date->format('M Y'),
                'samples' => Sample::whereBetween('created_at', [$monthStart, $monthEnd])
                    ->count(),
                'target' => $monthlyTarget,
            ];
        }

        return $rows;
    }

    private function countRequestsYearToDate(Carbon $end): int
