    }

    /**
     * Generate and save report.
     */
    public function generate(array $data, ?int $userId = null, bool $isAutoGenerated = false): ConsolidatedReport
    {
        $start = Carbon::parse($data['period_start'])->startOfDay();
        $end = Carbon::parse($data['period_end'])->endOfDay();
        $periodType = $data['period_type'];

        // Calculate period label for narrative replacement
        $periodLabel = $this->getPeriodLabel($periodType, $start, $end);

        // Process narratives to replace placeholders
        $narratives = $data['narratives'];
        if (isset($narratives['opening'])) {
            $narratives['opening'] = str_replace('{period_label}', $periodLabel, $narratives['opening']);
        }
        if (isset($narratives['closing'])) {
            $narratives['closing'] = str_replace('{period_label}', $periodLabel, $narratives['closing']);
        }

        // Prepare data structure
        $reportData = [
            'statistics' => $this->getStatisticsForPeriod($start, $end),
            'active_substances' => $this->getActiveSubstancesForPeriod($start, $end),
            'processing_time' => $this->getProcessingTimeBreakdown($start, $end),
            'satisfaction' => $this->getSatisfactionBreakdown($start, $end),
            'gender' => $this->getGenderBreakdown($start, $end),
            'jurisdiction' => $this->getJurisdictionBreakdown($start, $end),
            'age_range' => $this->getAgeRangeBreakdown($start, $end),
            'dashboard_appendix' => $this->getDashboardAppendixForPeriod($start, $end),
            'iku' => $periodType === 'quarterly' ? $this->ikuService->computeForPeriod($start, $end) : null,
        ];

        $this->assertSubstanceCoverage($reportData);

        $comparisonData = $this->getComparisonData($periodType, $start);

        return DB::transaction(function () use ($periodType, $start, $end, $reportData, $comparisonData, $narratives, $data, $userId, $isAutoGenerated): ConsolidatedReport {
            $report = ConsolidatedReport::create([
                'period_type' => $periodType,
                'period_start' => $start,
                'period_end' => $end,
                'period_label' => $this->getPeriodLabel($periodType, $start, $end),
                'report_data' => $reportData,
                'comparison_data' => $comparisonData,
                'narrative_sections' => $narratives,
                'signers' => $data['signers'],
                'generated_by' => $userId,
                'generated_at' => now(),
                'is_auto_generated' => $isAutoGenerated,
            ]);
            $this->generatePdf($report);

            return $report;
        });
    }

    /**
     * Get statistics for a specific period.
     */
    public function getStatisticsForPeriod(Carbon $start, Carbon $end): array
    {
        $requestsReceived = TestRequest::whereBetween('created_at', [$start, $end])->count();

        // FIX: Only count requests that are truly completed (picked up by investigator)
        // Status 'ready_for_delivery' means lab is done but NOT yet picked up
        // Status 'completed' or 'delivered' means actually picked up
        $requestsCompleted = TestRequest::whereIn('status', ['completed', 'delivered'])
            ->whereBetween('completed_at', [$start, $end])
            ->count();

        $samplesReceived = Sample::whereBetween('created_at', [$start, $end])->count();

        $samplesTested = $this->testedSamplesForPeriod($start, $end)->count();

        // LHU Terbit = Jumlah sampel dari request yang siap diambil pada periode tersebut
        // Setiap sampel menghasilkan satu LHU
        $lhuIssued = Sample::whereHas('testRequest', function ($query) use ($start, $end) {
            $query->whereNotNull('ready_for_delivery_at')
                ->whereBetween('ready_for_delivery_at', [$start, $end]);
        })->count();

        // Calculate average processing time (days)
        // FIX: Calculate from submitted_at to ready_for_delivery_at (weekdays only)
        $processingTimes = TestRequest::whereIn('status', ['completed', 'ready_for_delivery', 'delivered'])
            ->whereNotNull('ready_for_delivery_at')
            ->whereBetween('ready_for_delivery_at', [$start, $end])
            ->get()
            ->map(function ($req) {
                $startDate = $req->submitted_at ?? $req->created_at;
                $endDate = $req->ready_for_delivery_at;

                if (! $startDate || ! $endDate || $endDate->lt($startDate)) {
                    return 0;
                }

                return $startDate->diffInWeekdays($endDate);
            });

        $avgProcessingTime = (float) ($processingTimes->avg() ?? 0);

        // Calculate average satisfaction rating
        // FIX: Cast to float to avoid round() errors
        $avgSatisfaction = (float) (CustomerSurvey::whereBetween('submitted_at', [$start, $end])
            ->avg('score_avg') ?? 0);

        return [
            'total_requests_received' => $requestsReceived,
            'total_requests_completed' => $requestsCompleted,
            'total_samples_received' => $samplesReceived,
            'total_samples_tested' => $samplesTested,
            'total_lhu_issued' => $lhuIssued,
            'avg_processing_days' => round($avgProcessingTime, 1),
            'satisfaction_rating' => round($avgSatisfaction, 1),
        ];
    }

    /**
     * Get active substance breakdown for a specific period.
     */
    public function getActiveSubstancesForPeriod(Carbon $start, Carbon $end): array
    {
        $end = $end->copy()->endOfDay();
        $samples = $this->testedSamplesForPeriod($start, $end)
            ->withExists(['testProcesses as has_interpretation' => fn ($query) => $query->where('stage', 'interpretation')])
            ->with(['testProcesses' => function ($query) use ($end): void {
                $query->where('stage', 'interpretation')->whereNotNull('completed_at')
                    ->where('completed_at', '<=', $end)
                    ->orderByDesc('completed_at')->orderByDesc('id');
            }])->get();
        $legacyResults = TestResult::whereIn('sample_id', $samples->modelKeys())
            ->where('created_at', '<=', $end)
            ->where(fn ($query) => $query->whereNull('reviewed_at')->orWhere('reviewed_at', '<=', $end))
            ->orderByDesc('created_at')->orderByDesc('id')->get()->unique('sample_id')->keyBy('sample_id');
        $counts = [];
        $positive = 0;
        $negative = 0;
        $missing = 0;
        $fallback = 0;

        foreach ($samples as $sample) {
            $process = $sample->testProcesses->first();
            $substances = [];
            $complete = true;
            if ($process) {
                $metadata = $process->metadata ?? [];
                $secondary = $metadata['multi_interpretations'] ?? [];
                $entries = is_array($secondary) ? [$metadata, ...$secondary] : [$metadata, null];
                foreach ($entries as $entry) {
                    if (! is_array($entry)) {
                        $complete = false;

                        continue;
                    }
                    $state = $entry['test_result'] ?? null;
                    if ($state === 'negative') {
                        continue;
                    }
                    $detected = $this->extractActiveSubstances($entry['detected_substance'] ?? $entry['detection'] ?? null);
                    if ($detected === [] || ! in_array($state, [null, 'positive'], true)) {
                        $complete = false;
                    }
                    $substances = array_merge($substances, $detected);
                }
            } elseif ($legacyResults->has($sample->id)) {
                $result = $legacyResults->get($sample->id);
                $fallback++;
                if ($result->result_status !== 'negative') {
                    $substances = $this->extractActiveSubstances($result->active_substances);
                    $complete = $result->result_status === 'positive' && $substances !== [];
                }
            } elseif ($sample->has_interpretation) {
                // A draft or future interpretation is not a confirmed legacy result.
                $complete = false;
            } else {
                $fallback++;
                $substances = $this->extractActiveSubstances($sample->active_substance);
                $complete = $substances !== [];
            }

            if (! $complete) {
                $missing++;
            } elseif ($substances === []) {
                $negative++;
            } else {
                $positive++;
            }
            foreach ($this->normalizeActiveSubstanceParts($substances) as $substance) {
                $counts[$substance] = ($counts[$substance] ?? 0) + 1;
            }
        }

        arsort($counts);

        $totalSamples = array_sum($counts);
        $items = [];

        foreach ($counts as $displayName => $count) {
            $items[] = [
                'name' => $displayName,
                'count' => $count,
                'percentage' => $totalSamples > 0 ? round(($count / $totalSamples) * 100, 1) : 0,
            ];
        }

        return [
            'items' => $items,
            'total' => $totalSamples,
            'sample_total' => $samples->count(),
            'positive_samples' => $positive,
            'negative_samples' => $negative,
            'missing_result_samples' => $missing,
            'legacy_samples' => $fallback,
            'is_complete' => $missing === 0,
            'calculation_version' => 2,
            'message' => $missing > 0
                ? "Data hasil belum lengkap untuk {$missing} dari {$samples->count()} sampel teruji. Laporan belum dapat diterbitkan."
                : ($samples->isEmpty() ? 'Tidak ada sampel teruji pada periode ini.'
                    : ($positive === 0 ? 'Seluruh hasil pengujian yang terbaca pada periode ini negatif.' : '')),
        ];
    }

    private function testedSamplesForPeriod(Carbon $start, Carbon $end): Builder
    {
        $start = $start->copy()->startOfDay();
        $end = $end->copy()->endOfDay();

        // Keep the legacy completion fallback identical for the statistic and its breakdown.
        return Sample::whereIn('sample_status', ['ready_for_delivery', 'interpretation_done', 'tested', 'completed'])
            ->where(function ($query) use ($start, $end): void {
                $query->whereBetween('testing_completed_at', [$start, $end])
                    ->orWhere(fn ($query) => $query->whereNull('testing_completed_at')->whereBetween('updated_at', [$start, $end]));
            });
    }

    private function assertSubstanceCoverage(array $data): void
    {
        $substances = $data['active_substances'];
        if (! $substances['is_complete'] || $substances['sample_total'] !== (int) $data['statistics']['total_samples_tested']) {
            throw ValidationException::withMessages([
                'active_substances' => $substances['message'] ?: 'Jumlah sampel pada rekap zat aktif tidak sesuai dengan statistik sampel teruji. Muat ulang pratinjau.',
            ]);
        }
    }

    public function reviseActiveSubstances(ConsolidatedReport $original, string $reason, ?int $userId = null): ConsolidatedReport
    {
        if (trim($reason) === '') {
            throw ValidationException::withMessages(['reason' => 'Alasan revisi wajib diisi.']);
        }

        $revision = null;
        try {
            return DB::transaction(function () use ($original, $reason, $userId, &$revision): ConsolidatedReport {
                $original = ConsolidatedReport::query()->lockForUpdate()->findOrFail($original->id);
                if ($original->revision_of_id !== null) {
                    throw ValidationException::withMessages(['report' => 'Pilih laporan asli sebagai sumber revisi.']);
                }
                $existing = ConsolidatedReport::where('revision_of_id', $original->id)
                    ->where('report_data->active_substances->calculation_version', 2)->first();
                if ($existing) {
                    return $existing;
                }

                $data = $original->report_data;
                $data['active_substances'] = $this->getActiveSubstancesForPeriod($original->period_start, $original->period_end);
                $this->assertSubstanceCoverage($data);
                foreach ($data['dashboard_appendix']['summary_cards'] ?? [] as $key => $card) {
                    if (($card['label'] ?? null) === 'Zat Aktif Unik') {
                        $data['dashboard_appendix']['summary_cards'][$key]['value'] = count($data['active_substances']['items']);
                        $data['dashboard_appendix']['summary_cards'][$key]['note'] = 'Dihitung dari hasil sampel teruji pada periode ini';
                    }
                }
                foreach ($data['dashboard_appendix']['charts'] ?? [] as $key => $chart) {
                    if (($chart['title'] ?? null) === 'Jenis Zat Aktif') {
                        $data['dashboard_appendix']['charts'][$key] = $this->makeChartSection('Jenis Zat Aktif', 'doughnut',
                            array_map(fn ($item) => ['label' => $item['name'], 'count' => $item['count'], 'percentage' => $item['percentage']], $data['active_substances']['items']),
                            $data['active_substances']['total']);
                    }
                }
                $number = max((int) $original->revision_number,
                    (int) ConsolidatedReport::withTrashed()->where('revision_of_id', $original->id)->max('revision_number')) + 1;
                $revision = ConsolidatedReport::create([
                    'period_type' => $original->period_type,
                    'period_start' => $original->period_start,
                    'period_end' => $original->period_end,
                    'period_label' => $original->period_label,
                    'report_data' => $data,
                    'comparison_data' => $original->comparison_data,
                    'narrative_sections' => $original->narrative_sections,
                    'signers' => $original->signers,
                    'generated_by' => $userId,
                    'generated_at' => now(),
                    'is_auto_generated' => false,
                    'revision_of_id' => $original->id,
                    'revision_number' => $number,
                    'revision_reason' => trim($reason),
                ]);
                $this->generatePdf($revision);
                ActivityLogger::log('CONSOLIDATED_REPORT_SUBSTANCES_REVISED', subject: $revision,
                    before: ['report_id' => $original->id], after: ['report_id' => $revision->id],
                    meta: ['reason' => trim($reason), 'calculation_version' => 2, 'source' => 'console'], actorUserId: $userId);

                return $revision;
            });
        } catch (\Throwable $exception) {
            if ($revision?->pdf_path) {
                Storage::delete($revision->pdf_path);
            }
            throw $exception;
        }
    }

    /**
     * @return array<int, string>
     */
    private function extractActiveSubstances(mixed $raw): array
    {
        if ($raw === null || is_bool($raw) || is_numeric($raw)) {
            return [];
        }

        if (is_array($raw)) {
            $collected = [];

            foreach ($raw as $item) {
                $collected = array_merge($collected, $this->extractActiveSubstances($item));
            }

            return $this->normalizeActiveSubstanceParts($collected);
        }

        $rawString = trim((string) $raw);
        if ($rawString === '') {
            return [];
        }

        $decoded = json_decode($rawString, true);
        if (json_last_error() === JSON_ERROR_NONE && (is_array($decoded) || is_string($decoded))) {
            return $this->extractActiveSubstances($decoded);
        }

        return $this->normalizeActiveSubstanceParts(preg_split('/[,;\n]+/', $rawString) ?: []);
    }

    /**
     * @param  array<int, mixed>  $parts
     * @return array<int, string>
     */
    private function normalizeActiveSubstanceParts(array $parts): array
    {
        return collect($parts)
            ->map(fn ($part) => trim((string) $part))
            ->filter()
            ->map(fn (string $part) => ucwords(strtolower($part)))
            ->reject(fn (string $part) => in_array(strtolower($part), ['-', 'n/a', 'null', 'none', 'negative', 'negatif', 'tidak terdeteksi', 'tidak ada hasil terdeteksi', 'tidak ada', 'tidak diketahui'], true))
            ->unique()
            ->values()
            ->all();
    }

    /**
     * Get processing time breakdown for a period.
     */
    public function getProcessingTimeBreakdown(Carbon $start, Carbon $end): array
    {
        $requests = TestRequest::whereIn('status', ['completed', 'ready_for_delivery', 'delivered'])
            ->whereNotNull('ready_for_delivery_at')
            ->whereBetween('ready_for_delivery_at', [$start, $end])
            ->get()
            ->map(function ($req) {
                $startDate = $req->submitted_at ?? $req->created_at;
                $endDate = $req->ready_for_delivery_at;

                if (! $startDate || ! $endDate || $endDate->lt($startDate)) {
                    return 0;
                }

                return $startDate->diffInWeekdays($endDate);
            });

        $total = $requests->count();

        $categories = [
            '≤ 3 hari' => $requests->filter(fn ($d) => $d <= 3)->count(),
            '4-7 hari' => $requests->filter(fn ($d) => $d >= 4 && $d <= 7)->count(),
            '8-14 hari' => $requests->filter(fn ($d) => $d >= 8 && $d <= 14)->count(),
            '> 14 hari' => $requests->filter(fn ($d) => $d > 14)->count(),
        ];

        return [
            'categories' => collect($categories)->map(fn ($count, $label) => [
                'label' => $label,
                'count' => $count,
                'percentage' => $total > 0 ? round(($count / $total) * 100, 1) : 0,
            ])->values()->toArray(),
            'total' => $total,
            'avg_days' => $total > 0 ? round($requests->avg(), 1) : 0,
        ];
    }

    /**
     * Get customer satisfaction breakdown for a period.
     */
    public function getSatisfactionBreakdown(Carbon $start, Carbon $end): array
    {
        $surveys = CustomerSurvey::whereBetween('submitted_at', [$start, $end])
            ->whereNotNull('score_avg')
            ->get();

        $total = $surveys->count();
        $avgScore = (float) ($surveys->avg('score_avg') ?? 0);

        // Group by rounded score (1-4)
        $ratings = [
            4 => ['label' => 'Sangat Puas (4)', 'count' => 0],
            3 => ['label' => 'Puas (3)', 'count' => 0],
            2 => ['label' => 'Kurang Puas (2)', 'count' => 0],
            1 => ['label' => 'Tidak Puas (1)', 'count' => 0],
        ];

        foreach ($surveys as $survey) {
            $rounded = (int) round((float) $survey->score_avg);
            $rounded = max(1, min(4, $rounded)); // Clamp 1-4
            $ratings[$rounded]['count']++;
        }

        return [
            'ratings' => collect($ratings)->map(fn ($r) => [
                'label' => $r['label'],
                'count' => $r['count'],
                'percentage' => $total > 0 ? round(($r['count'] / $total) * 100, 1) : 0,
            ])->values()->toArray(),
            'total_respondents' => $total,
            'avg_score' => round($avgScore, 2),
        ];
    }

    /**
     * Get suspect gender breakdown for a period.
     */
    public function getGenderBreakdown(Carbon $start, Carbon $end): array
    {
        $requests = TestRequest::whereBetween('created_at', [$start, $end])
            ->select('suspect_gender', DB::raw('count(*) as total'))
            ->groupBy('suspect_gender')
            ->get();

        // Normalize gender variations (male/female, Laki-laki/Perempuan, L/P, etc)
        $maleCount = 0;
        $femaleCount = 0;
        $unknownCount = 0;

        foreach ($requests as $req) {
            $gender = strtolower(trim($req->suspect_gender ?? ''));

            if (in_array($gender, ['l', 'laki-laki', 'laki', 'pria', 'male', 'm'])) {
                $maleCount += $req->total;
            } elseif (in_array($gender, ['p', 'perempuan', 'wanita', 'female', 'f'])) {
                $femaleCount += $req->total;
            } else {
                $unknownCount += $req->total;
            }
        }

        $total = $maleCount + $femaleCount + $unknownCount;

        $genders = [
            ['label' => 'Laki-laki', 'count' => $maleCount],
            ['label' => 'Perempuan', 'count' => $femaleCount],
            ['label' => 'Tidak Diketahui', 'count' => $unknownCount],
        ];

        return [
            'items' => collect($genders)->map(fn ($g) => [
                'label' => $g['label'],
                'count' => $g['count'],
                'percentage' => $total > 0 ? round(($g['count'] / $total) * 100, 1) : 0,
            ])->toArray(),
            'total' => $total,
        ];
    }

    /**
     * Get jurisdiction (asal user) breakdown for a period.
     */
    public function getJurisdictionBreakdown(Carbon $start, Carbon $end): array
    {
        $data = TestRequest::whereBetween('test_requests.created_at', [$start, $end])
            ->join('investigators', 'test_requests.investigator_id', '=', 'investigators.id')
            ->select('investigators.jurisdiction', DB::raw('count(*) as total'))
            ->groupBy('investigators.jurisdiction')
            ->orderByDesc('total')
            ->limit(10)
            ->get();

        $total = TestRequest::whereBetween('created_at', [$start, $end])->count();

        return [
            'items' => $data->map(fn ($item) => [
                'label' => $item->jurisdiction ?: 'Tidak Diketahui',
                'count' => $item->total,
                'percentage' => $total > 0 ? round(($item->total / $total) * 100, 1) : 0,
            ])->toArray(),
            'total' => $total,
        ];
    }

    /**
     * Get suspect age range breakdown for a period.
     */
    public function getAgeRangeBreakdown(Carbon $start, Carbon $end): array
    {
        $requests = TestRequest::whereBetween('created_at', [$start, $end])
            ->whereNotNull('suspect_age')
            ->pluck('suspect_age');

        $nullCount = TestRequest::whereBetween('created_at', [$start, $end])
            ->whereNull('suspect_age')
            ->count();

        $total = $requests->count() + $nullCount;

        $ranges = [
            '< 18 tahun' => $requests->filter(fn ($a) => $a < 18)->count(),
            '18-25 tahun' => $requests->filter(fn ($a) => $a >= 18 && $a <= 25)->count(),
            '26-35 tahun' => $requests->filter(fn ($a) => $a >= 26 && $a <= 35)->count(),
            '36-45 tahun' => $requests->filter(fn ($a) => $a >= 36 && $a <= 45)->count(),
            '46-55 tahun' => $requests->filter(fn ($a) => $a >= 46 && $a <= 55)->count(),
            '> 55 tahun' => $requests->filter(fn ($a) => $a > 55)->count(),
            'Tidak Diketahui' => $nullCount,
        ];

        return [
            'items' => collect($ranges)->map(fn ($count, $label) => [
                'label' => $label,
                'count' => $count,
                'percentage' => $total > 0 ? round(($count / $total) * 100, 1) : 0,
            ])->values()->toArray(),
            'total' => $total,
        ];
    }

    /**
     * Get comparison data with previous period.
     */
    public function getComparisonData(string $periodType, Carbon $currentStart): array
    {
        // Determine previous period range
        $prevStart = $currentStart->copy();
        $prevEnd = $currentStart->copy();

        switch ($periodType) {
            case 'biweekly':
                if ($currentStart->day <= 15) {
                    // Previous is 16-end of last month
                    $prevStart = $prevStart->subMonth()->startOfMonth()->addDays(15);
                    $prevEnd = $prevEnd->subMonth()->endOfMonth();
                } else {
                    // Previous is 1-15 of current month
                    $prevStart = $prevStart->startOfMonth();
                    $prevEnd = $prevEnd->startOfMonth()->addDays(14)->endOfDay();
                }
                break;
            case 'monthly':
                $prevStart->subMonth()->startOfMonth();
                $prevEnd->subMonth()->endOfMonth();
                break;
            case 'quarterly':
                $prevStart->subQuarter()->startOfQuarter();
                $prevEnd->subQuarter()->endOfQuarter();
                break;
        }

        $currentStats = $this->getStatisticsForPeriod($currentStart, $this->getPeriodEnd($periodType, $currentStart));
        $prevStats = $this->getStatisticsForPeriod($prevStart, $prevEnd);

        $changes = [];
        foreach ($currentStats as $key => $val) {
            $prevVal = $prevStats[$key] ?? 0;
            $diff = $val - $prevVal;

            // Avoid division by zero
            $diffPercent = $prevVal > 0 ? round(($diff / $prevVal) * 100, 1) : 0;
            if ($prevVal == 0 && $val > 0) {
                $diffPercent = 100;
            }

            $changes[$key] = [
                'previous' => $prevVal,
                'current' => $val,
                'diff' => $diff,
                'diff_percent' => $diffPercent,
            ];
        }

        return [
            'previous_period' => [
                'start' => $prevStart->toDateString(),
                'end' => $prevEnd->toDateString(),
                'label' => $this->getPeriodLabel($periodType, $prevStart, $prevEnd),
            ],
            'changes' => $changes,
        ];
    }

