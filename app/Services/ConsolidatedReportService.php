    public function getDefaultSigners(): array
    {
        $signers = $this->settings->get('consolidated_report.default_signers', null);

        if (empty($signers)) {
            return self::DEFAULT_SIGNERS_STRUCTURE;
        }

        return $signers;
    }

    /**
     * Generate PDF file and update record.
     */
    public function generatePdf(ConsolidatedReport $report): void
    {
        $pdf = Pdf::loadView('pdf.consolidated-report', ['report' => $report])
            ->setPaper('a4', 'portrait');

        $filename = "laporan-{$report->period_type}-{$report->period_start->format('Ymd')}.pdf";
        $path = "reports/consolidated/{$filename}";

        Storage::put($path, $pdf->output());

        $report->update([
            'pdf_path' => $path,
            'pdf_size' => Storage::size($path),
        ]);
    }

    private function getPeriodLabel(string $type, Carbon $start, Carbon $end): string
    {
        Carbon::setLocale('id');

        return match ($type) {
            'biweekly' => 'Bi-weekly '.$start->format('d').'-'.$end->translatedFormat('d F Y'),
            'monthly' => 'Bulan '.$start->translatedFormat('F Y'),
            'quarterly' => 'Triwulan '.$start->quarter.' Tahun '.$start->year,
            default => $start->format('d/m/Y').' - '.$end->format('d/m/Y'),
        };
    }

    private function getPeriodEnd(string $type, Carbon $start): Carbon
    {
        $end = $start->copy();

        return match ($type) {
            'biweekly' => $start->day <= 15 ? $end->startOfMonth()->addDays(14)->endOfDay() : $end->endOfMonth(),
            'monthly' => $end->endOfMonth(),
            'quarterly' => $end->endOfQuarter(),
            default => $end,
        };
    }

    /**
     * Send notification for generated report.
     */
    public function sendGenerationNotification(ConsolidatedReport $report, bool $force = false): int
    {
        // Check if notification is enabled
        $notifyEnabled = (bool) $this->settings->get('consolidated_report.notify_on_generate', true);

        if (! $notifyEnabled) {
            return 0;
        }

        // Determine target phone
        $targetPhone = $this->settings->get('consolidated_report.notify_phone');
        if (empty($targetPhone)) {
            $targetPhone = '+6285956592404'; // Default fallback
        }

        $normalizedPhone = $this->normalizePhone((string) $targetPhone);
        $normalizedJid = $normalizedPhone.'@s.whatsapp.net';

        if (! $force && $this->hasNotificationQueuedOrSent($report, $normalizedJid)) {
            Log::info("Consolidated report notification already queued/sent for report {$report->id} to {$normalizedJid}");

            return 0;
        }

        // Format message
        $reportUrl = self::PUBLIC_REPORT_URL;
        $generatedAt = $report->generated_at ? $report->generated_at->format('d/m/Y H:i') : now()->format('d/m/Y H:i');

        $templateKey = $this->resolveConsolidatedTemplateKey((string) $report->period_type);
        $message = $this->templateService->render('system', $templateKey, [
            'period_type' => (string) $report->period_type,
            'period_label' => (string) $report->period_label,
            'period_start' => $report->period_start->format('d/m/Y'),
            'period_end' => $report->period_end->format('d/m/Y'),
            'generated_at' => $generatedAt,
            'total_requests' => (string) ($report->report_data['statistics']['total_requests_received'] ?? 0),
            'total_samples' => (string) ($report->report_data['statistics']['total_samples_received'] ?? 0),
            'report_url' => $reportUrl,
        ]);

        if (trim($message) === '') {
            $message = $this->buildFallbackConsolidatedMessage($report, $generatedAt, $reportUrl);
        }

        try {
            // Create batch record
            $batch = WhatsAppMessageBatch::create([
                'type' => 'consolidated_report_notification',
                'source_type' => ConsolidatedReport::class,
                'source_id' => $report->id,
                'title' => "Laporan {$report->period_label}",
                'message_preview' => mb_strimwidth($message, 0, 100, '...'),
                'total_recipients' => 1,
                'sent_count' => 0,
                'failed_count' => 0,
                'mention_all' => false,
                'started_at' => now(),
                'created_by' => $report->generated_by,
            ]);

            WhatsAppMessageLog::create([
                'batch_id' => $batch->id,
                'recipient_jid' => $normalizedJid,
                'recipient_name' => $normalizedPhone,
                'recipient_type' => 'individual',
                'status' => 'pending',
            ]);

            $attachmentPath = $this->resolvePdfAbsolutePath($report);
            $attachmentFilename = $attachmentPath ? basename((string) $report->pdf_path) : null;

            // Dispatch job (dengan attachment PDF jika tersedia)
            SendWhatsAppMessage::dispatch(
                $normalizedPhone,
                $message,
                $batch->id,
                $attachmentPath,
                $attachmentFilename
            );

            Log::info("Consolidated report notification queued for {$normalizedPhone}");

            return 1;
        } catch (\Exception $e) {
            Log::error("Failed to send consolidated report notification: {$e->getMessage()}");

            return 0;
        }
    }

    private function hasNotificationQueuedOrSent(ConsolidatedReport $report, string $recipientJid): bool
    {
        $reportIds = ConsolidatedReport::query()
            ->where('period_type', (string) $report->period_type)
            ->whereDate('period_start', $report->period_start->toDateString())
            ->whereDate('period_end', $report->period_end->toDateString())
            ->pluck('id');

        if ($reportIds->isEmpty()) {
            return false;
        }

        return WhatsAppMessageBatch::query()
            ->where('type', 'consolidated_report_notification')
            ->where('source_type', ConsolidatedReport::class)
            ->whereIn('source_id', $reportIds->all())
            ->whereHas('logs', function ($query) use ($recipientJid) {
                $query->where('recipient_jid', $recipientJid)
                    ->whereIn('status', ['pending', 'processing', 'sent']);
            })
            ->exists();
    }

    private function resolveConsolidatedTemplateKey(string $periodType): string
    {
        return match ($periodType) {
            'biweekly' => 'CONSOLIDATED_BIWEEKLY',
            'monthly' => 'CONSOLIDATED_MONTHLY',
            'quarterly' => 'CONSOLIDATED_QUARTERLY',
            default => 'CONSOLIDATED_BIWEEKLY',
        };
    }

    private function buildFallbackConsolidatedMessage(ConsolidatedReport $report, string $generatedAt, string $reportUrl): string
    {
        $message = "📊 *LAPORAN GABUNGAN PERIODIK*\n\n";
        $message .= "Laporan {$report->period_type} periode {$report->period_label} telah di-generate.\n\n";
        $message .= "📅 Periode: {$report->period_start->format('d/m/Y')} - {$report->period_end->format('d/m/Y')}\n";
        $message .= "⏰ Waktu Generate: {$generatedAt}\n";
        $message .= '📈 Total Permintaan: '.($report->report_data['statistics']['total_requests_received'] ?? 0)."\n";
        $message .= '🧪 Total Sampel: '.($report->report_data['statistics']['total_samples_received'] ?? 0)."\n\n";
        $message .= "Silakan akses laporan di:\n";
        $message .= "{$reportUrl}\n\n";
        $message .= "—\n";
        $message .= 'Staff Laboratorium Farmapol Pusdokkes Polri';

        return $message;
    }

    private function resolvePdfAbsolutePath(ConsolidatedReport $report): ?string
    {
        $pdfPath = trim((string) ($report->pdf_path ?? ''));
        if ($pdfPath === '') {
            return null;
        }

        if (! Storage::exists($pdfPath)) {
            return null;
        }

        try {
            $absolutePath = Storage::path($pdfPath);
        } catch (\Throwable) {
            return null;
        }

        return is_readable($absolutePath) ? $absolutePath : null;
    }

    private function normalizePhone(string $phone): string
    {
        $phone = preg_replace('/[^0-9]/', '', $phone) ?? '';
        if ($phone !== '' && str_starts_with($phone, '0')) {
            $phone = '62'.substr($phone, 1);
        }

        return $phone;
    }

    /**
     * Determine if reports should be auto-generated today.
     */
    public function shouldAutoGenerate(): array
    {
        $today = Carbon::now('Asia/Jakarta');
        $reports = [];

        // Bi-weekly: Generate only on 16th (for 1-15 period)
        // Note: 16-31 is NOT auto-generated as it's covered by the monthly report
        if ($today->day === 16) {
            $reports[] = [
                'type' => 'biweekly',
                'start' => $today->copy()->startOfMonth(),
                'end' => $today->copy()->startOfMonth()->addDays(14)->endOfDay(),
            ];
        }

        if ($today->day === 1) {
            // Monthly for previous month
            $reports[] = [
                'type' => 'monthly',
                'start' => $today->copy()->subMonth()->startOfMonth(),
                'end' => $today->copy()->subMonth()->endOfMonth(),
            ];

            // Quarterly on Jan 1, Apr 1, Jul 1, Oct 1
            if (in_array($today->month, [1, 4, 7, 10])) {
                $quarterStart = $today->copy()->subQuarter()->startOfQuarter();
                $reports[] = [
                    'type' => 'quarterly',
                    'start' => $quarterStart,
                    'end' => $quarterStart->copy()->endOfQuarter(),
                ];
            }
        }

        return $reports;
    }
